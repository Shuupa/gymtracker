/// Норма силы для упражнения.
///
/// Обычные упражнения: отношение расчётного 1RM к весу тела.
/// Для гантелей вводи вес ОДНОЙ гантели.
/// repBased (свой вес): число повторений. Добавочный вес «утяжеляет»
/// повторы. Для планки вводи секунды в поле «Повторы».
class Standard {
  /// [начальный, новичок, средний, продвинутый, элита] для мужчин
  final List<double> male;
  final bool repBased;
  const Standard(this.male, {this.repBased = false});

  /// 0..1: 0.2 = достиг «начальный», 0.4 = «новичок», ... 1.0 = «элита»
  double score(double value, bool isMale) {
    if (value <= 0) return 0;
    final k = isMale ? 1.0 : (repBased ? 0.7 : 0.6);
    final pts = [0.0, ...male.map((v) => v * k)];
    for (var i = 1; i < pts.length; i++) {
      if (value <= pts[i]) {
        final t = (value - pts[i - 1]) / (pts[i] - pts[i - 1]);
        return ((i - 1) + t) * 0.2;
      }
    }
    return 1.0;
  }
}

